'use strict';
const assert=require('node:assert/strict');
const M=require('./dist/model.js');
const seedFixture=require('./test-fixture.cjs');
const state=M.upgrade(seedFixture('2026-10-20'));
assert.equal(M.validState(state),true);
assert.equal(M.monday('2026-10-20'),'2026-10-19');
assert.equal(M.addDays('2026-12-31',1),'2027-01-01');
assert.equal(M.shiftMonth('2024-01-31',1),'2024-02-29');
assert.deepEqual(M.periodBounds('quarter','2026-12-31'),['2026-10-01','2026-12-31']);
assert.deepEqual(M.periodBounds('five','2026-10-20'),['2026-01-01','2030-12-31']);
assert.equal(M.goalTrail(state.goals,'VIU-week').length,5);
assert.equal(M.parentError(state.goals,{...state.goals.find(g=>g.id==='VIU-week'),company:'RET'},state.companies),'La meta superior debe ser del mismo negocio.');
assert.ok(M.parentError(state.goals,{...state.goals.find(g=>g.id==='VIU-five'),parentId:'VIU-week'},state.companies));
assert.ok(M.parentError(state.goals,{...state.goals.find(g=>g.id==='VIU-month'),end:'2026-10-18'},state.companies));
assert.equal(M.parentError(state.goals,{id:'overlap',title:'Semana entre dos meses',company:'VIU',level:'week',parentId:'VIU-month',start:'2026-10-26',end:'2026-11-01'},state.companies),'');
assert.ok(M.priorityError(state.tasks,{id:'fourth',date:'2026-10-20',priority:true}));
assert.equal(M.priorityError(state.tasks,{...state.tasks[0],priority:true}),'');
assert.ok(M.priorityError(state.tasks,{id:'undated',date:null,priority:true}));
assert.equal(M.progress(state,'VIU-five').done,0);
state.tasks.find(t=>t.id==='viu-activate').done=true;
assert.equal(M.progress(state,'VIU-five').done,1);
assert.equal(M.habitDue({days:[0]},'2026-10-19'),true);
assert.equal(M.habitDue({days:[0]},'2026-10-20'),false);
assert.equal(M.activity(state,'2026-01-01','2026-12-31'),0);
state.completionEvents.push({taskId:'one',done:true,company:'VIU',on:'2026-10-20'});
assert.equal(M.activity(state,'2026-10-19','2026-10-25','VIU'),1);
assert.equal(M.activity(state,'2026-10-19','2026-10-25','RET'),0);
state.completionEvents.push({taskId:'one',done:false,company:'VIU',on:'2026-10-20'});
assert.equal(M.activity(state,'2026-10-19','2026-10-25'),0);
state.companies['B-test']={name:'Mi negocio',color:'#507ba0',bg:'#e5eef7'};
assert.equal(M.parentError(state.goals,{id:'new',title:'Mi meta',company:'B-test',level:'year',start:'2026-01-01',end:'2026-12-31',parentId:null},state.companies),'');
assert.equal(M.validState(state),true);
console.log('24 comprobaciones de fechas, jerarquía, prioridades, actividad y negocios: OK');
